"""
Writes the parts of the documentation that can be read straight from the code, so they cannot drift:
  data-dictionary.md   every model and field
  api-table.md         every API endpoint, method and who may call it
  er-diagram.md        a Mermaid ER diagram built from the real foreign keys
Run:  python manage.py generate_docs           (rewrite docs/generated/)
      python manage.py generate_docs --check   (exit 1 if the files are out of date; a test runs this)
"""
import os

from django.apps import apps as django_apps
from django.db import models as dj

from core.api_matrix import discover_routes
from core.models import BaseModel

APPS_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE_FIELDS = {'id', 'created_at', 'updated_at', 'is_deleted'}
HEADER = '<!-- Generated by `python manage.py generate_docs`. Do not edit by hand: change the code, then run the command. -->\n\n'


def our_models():
    """[(app name, [models])] for the project's own apps, in a stable order."""
    found = {}
    for config in django_apps.get_app_configs():
        if not os.path.abspath(config.path).startswith(APPS_DIR):
            continue
        found[config.name] = sorted(config.get_models(), key=lambda m: m.__name__)
    return sorted((name, mods) for name, mods in found.items() if mods)


def _type(field):
    kind = field.get_internal_type()
    if isinstance(field, dj.ForeignKey):
        return f'FK to {field.related_model._meta.app_label}.{field.related_model.__name__}'
    if isinstance(field, dj.OneToOneField):
        return f'One-to-one to {field.related_model.__name__}'
    if kind == 'CharField':
        return f'Char({field.max_length})'
    if kind == 'DecimalField':
        return f'Decimal({field.max_digits},{field.decimal_places})'
    return kind.replace('Field', '')


def _default(field):
    if field.has_default():
        value = field.default
        if callable(value):
            return f'{getattr(value, "__name__", "auto")}()'
        return repr(value)
    return ''


def _notes(field):
    notes = []
    if getattr(field, 'unique', False) and not field.primary_key:
        notes.append('unique')
    if field.null:
        notes.append('can be empty (null)')
    if field.choices:
        notes.append('one of: ' + ', '.join(str(c[0]) for c in field.choices))
    if isinstance(field, (dj.ForeignKey, dj.OneToOneField)):
        notes.append('on delete: ' + field.remote_field.on_delete.__name__)
    return '; '.join(notes)


def _constraints(model):
    rows = []
    for c in model._meta.constraints:
        rows.append(f'`{c.name}` ({type(c).__name__.replace("Constraint", "").lower()})')
    for group in model._meta.unique_together:
        rows.append('unique together: ' + ', '.join(group))
    return rows


def data_dictionary(level=2, standalone=True):
    out = ([HEADER, '# Data dictionary\n\n'] if standalone else [])
    out.append('Read from the Django models. Every model also has `id` (UUID, primary key), `created_at`, `updated_at` '
               'and `is_deleted` (from `core.BaseModel`) unless noted.\n\n')
    h_app, h_model = '#' * level, '#' * (level + 1)
    count = 0
    for app, models_ in our_models():
        out.append(f'{h_app} App `{app}`\n\n')
        for model in models_:
            count += 1
            fields = [f for f in model._meta.get_fields() if not f.auto_created and not f.is_relation or
                      (f.is_relation and f.concrete)]
            fields = [f for f in fields if f.name not in (BASE_FIELDS if issubclass(model, BaseModel) else set())]
            doc = (model.__doc__ or '').strip().splitlines()
            doc = doc[0] if doc and not doc[0].startswith(model.__name__ + '(') else ''
            out.append(f'{h_model} {model.__name__}\n\n')
            if doc:
                out.append(f'{doc}\n\n')
            out.append('| Field | Type | Default | Notes |\n|---|---|---|---|\n')
            for f in fields:
                out.append(f'| `{f.name}` | {_type(f)} | {_default(f)} | {_notes(f)} |\n')
            for f in model._meta.many_to_many:
                out.append(f'| `{f.name}` | Many-to-many to {f.related_model.__name__} | | |\n')
            for rule in _constraints(model):
                out.append(f'\nRule: {rule}\n')
            if not issubclass(model, BaseModel):
                out.append('\n(Does not use `BaseModel`: has its own key and timestamps.)\n')
            out.append('\n')
    out.append(f'*{count} models.*\n')
    return ''.join(out)


def _who(route, method):
    classes = route.permission_class_names()
    if 'IsPlatformAdmin' in classes:
        return 'Platform Admin'
    if route.template in ('api/v1/auth/login/', 'api/v1/auth/refresh/', 'api/v1/auth/logout/', 'api/v1/auth/register/'):
        return 'Public'
    permission = route.required_permission(method)
    return f'Permission `{permission}`' if permission else 'Any logged-in employee'


def api_table(standalone=True):
    routes = discover_routes()
    out = ([HEADER, '# API table\n\n'] if standalone else [])
    out += ['Every endpoint under `/api/v1/`, read from the URL configuration. `{id}` is a record id. '
           '"Who" is what the server checks: a Permission codename, or only a login (the service then checks '
           'ownership, for example the assignee or the approver).\n\n',
           '| Method | Endpoint | View / action | Who |\n|---|---|---|---|\n']
    count = 0
    for route in routes:
        path = '/' + route.template.replace('{pk}', '{id}')
        for method in sorted(route.methods, key=lambda m: ('get', 'post', 'put', 'patch', 'delete').index(m) if m in ('get', 'post', 'put', 'patch', 'delete') else 9):
            count += 1
            action = route.methods[method]
            view = route.view_cls.__name__ + (f' / {action}' if action else '')
            out.append(f'| {method.upper()} | `{path}` | {view} | {_who(route, method)} |\n')
    out.append(f'\n*{count} endpoint methods on {len(routes)} routes.*\n')
    return ''.join(out)


def er_diagram(standalone=True):
    models_ = [m for _app, ms in our_models() for m in ms]
    names = [m.__name__ for m in models_]
    clash = {n for n in names if names.count(n) > 1}

    def label(model):
        name = model.__name__.upper()
        return f'{model._meta.app_label.upper()}_{name}' if model.__name__ in clash else name

    out = ([HEADER, '# ER diagram\n\n'] if standalone else [])
    out += ['Built from the real foreign keys. `id`, timestamps and `is_deleted` are on every model and are not drawn. '
           'Links through `GenericForeignKey` (an approval or a notification pointing at any record) are not drawn.\n\n',
           '```mermaid\nerDiagram\n']
    lines = []
    for model in models_:
        for f in model._meta.get_fields():
            if not f.is_relation or f.auto_created or not f.concrete and not f.many_to_many:
                continue
            if f.related_model is None or f.related_model not in models_:
                continue
            target, source = label(f.related_model), label(model)
            if isinstance(f, dj.ManyToManyField):
                lines.append(f'  {source} }}o--o{{ {target} : {f.name}')
            elif isinstance(f, dj.OneToOneField):
                lines.append(f'  {target} ||--o| {source} : {f.name}')
            else:
                bar = '|o' if f.null else '||'
                lines.append(f'  {target} {bar}--o{{ {source} : {f.name}')
    out.append('\n'.join(sorted(set(lines))) + '\n')
    for model in models_:
        cols = [f for f in model._meta.concrete_fields if f.name not in BASE_FIELDS]
        out.append(f'  {label(model)} {{\n')
        for f in cols:
            kind = _type(f).split(' to ')[0].replace('FK', 'fk').replace(' ', '_').replace('(', '').replace(')', '').replace(',', '_')
            out.append(f'    {kind} {f.name}\n')
        out.append('  }\n')
    out.append('```\n')
    return ''.join(out)


def structure_tree():
    backend = os.path.dirname(APPS_DIR)
    repo = os.path.dirname(backend)
    skip = {'__pycache__', 'node_modules', 'dist', '.git', 'venv', 'migrations'}
    lines = ['```', 'backend/']
    top = sorted(f for f in os.listdir(backend) if os.path.isfile(os.path.join(backend, f)) and not f.endswith('.pyc') and f != 'db.sqlite3')
    lines.append('  ' + ', '.join(top))
    lines.append('  config/   settings/ (' + ', '.join(sorted(f[:-3] for f in os.listdir(os.path.join(backend, 'config', 'settings')) if f.endswith('.py') and f != '__init__.py')) + '), urls.py, wsgi.py, asgi.py')
    lines.append('  apps/')
    for app in sorted(d for d in os.listdir(APPS_DIR) if os.path.isfile(os.path.join(APPS_DIR, d, '__init__.py'))):
        base = os.path.join(APPS_DIR, app)
        files = sorted(f for f in os.listdir(base) if f.endswith('.py') and f != '__init__.py' and not f.startswith('test'))
        tests = sorted(f for f in os.listdir(base) if f.startswith('test') and f.endswith('.py'))
        extra = []
        mig = os.path.join(base, 'migrations')
        if os.path.isdir(mig):
            extra.append(f'migrations/ ({len([f for f in os.listdir(mig) if f[:4].isdigit()])})')
        if os.path.isdir(os.path.join(base, 'management')):
            cmds = os.path.join(base, 'management', 'commands')
            extra.append('commands: ' + ', '.join(sorted(f[:-3] for f in os.listdir(cmds) if f.endswith('.py') and f != '__init__.py')))
        lines.append(f'    {app}/  ' + ', '.join(files + extra) + ('  (+ tests)' if tests else ''))
    tests_dir = os.path.join(backend, 'tests')
    if os.path.isdir(tests_dir):
        lines.append('  tests/   browser (Selenium) test files, selenium_helpers.py, selenium_runner.py')
    lines.append('')
    lines.append('frontend/src/')
    src_dir = os.path.join(repo, 'frontend', 'src')
    if os.path.isdir(src_dir):
        for root, dirs, files in sorted(os.walk(src_dir)):
            dirs[:] = sorted(d for d in dirs if d not in skip)
            rel = os.path.relpath(root, src_dir)
            names = sorted(f for f in files if f.endswith(('.jsx', '.js')))
            if names:
                lines.append(f'  {"" if rel == "." else rel.replace(os.sep, "/") + "/"}  ' + ', '.join(names))
    lines.append('```')
    return '\n'.join(lines) + '\n'


def traceability_table():
    from core import traceability
    return traceability.table()


# name -> (standalone file text, text injected into a document, the document that holds the block)
BLOCKS = {
    'data-dictionary': (lambda: data_dictionary(2, True), lambda: data_dictionary(3, False), 'Ordinis_SDS.md'),
    'api-table': (lambda: api_table(True), lambda: api_table(False), 'Ordinis_SDS.md'),
    'er-diagram': (lambda: er_diagram(True), lambda: er_diagram(False), 'ordinis-ER-diagram.md'),
    'structure': (lambda: HEADER + '# Project structure\n\n' + structure_tree(), structure_tree, 'ordinis-project-structure.md'),
    'traceability': (lambda: HEADER + '# Requirements traceability\n\n' + traceability_table(), traceability_table, 'Ordinis_SRS.md'),
}


def marker(name, which):
    return f'<!-- {which} GENERATED:{name} -->'


def inject(text, name, content):
    """Replace what is between the BEGIN and END markers of block `name`. None when the markers are missing."""
    begin, end = marker(name, 'BEGIN'), marker(name, 'END')
    i, j = text.find(begin), text.find(end)
    if i < 0 or j < i:
        return None
    return text[:i + len(begin)] + '\n' + content.rstrip('\n') + '\n' + text[j:]


def standalone_files():
    return {f'{name}.md': pair[0]() for name, pair in BLOCKS.items()}


def out_dir():
    return os.path.join(os.path.dirname(os.path.dirname(APPS_DIR)), 'docs', 'generated')


def docs_dir():
    return os.path.dirname(out_dir())
